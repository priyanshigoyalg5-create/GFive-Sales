#!/usr/bin/env python3
"""Headless-browser smoke test of the DEMO build (needs: pip install playwright && playwright install chromium).
Usage: python3 tools/smoke_test.py demo/gfive-demo.html
It exercises the main flows with the in-memory fake Firebase and prints PASS/FAIL lines."""
import sys,os
from playwright.sync_api import sync_playwright
path="file://"+os.path.abspath(sys.argv[1]); errs=[]; res=[]
def chk(name,cond): res.append((name,bool(cond))); print(("PASS " if cond else "FAIL ")+name)
with sync_playwright() as p:
    b=p.chromium.launch(); pg=b.new_page(viewport={"width":420,"height":900})
    pg.on("pageerror",lambda e:errs.append(str(e))); pg.route("**/*xlsx*",lambda r:r.abort())
    pg.goto(path); pg.wait_for_timeout(700); pg.evaluate("window.print=()=>{}")
    tabs=[x.inner_text() for x in pg.locator("nav button").all()]
    chk("super sees TNA, Cost, Ledger",all(t in tabs for t in ["TNA","Cost","Ledger"]))
    # issue with two items from a (simulated) AI result
    pg.locator("nav button",has_text="Issue").first.click()
    pg.evaluate("""()=>fillAI({challan:'1551',date:'2026-08-18',karigar:'RUSTAM',items:[{design:'sd 11071',jobCard:'P256',colour:'P53',topFab:'F158',total:5.75,qty:30,rate:425},{design:'SD-11071',jobCard:'P256',colour:'P54',topFab:'F158',total:5.75,qty:20,rate:425}]},'issues')""")
    chk("total 5.75 splits into 3.15 + 2.6",pg.evaluate("f_topMtr.value+'/'+f_dupMtr.value")=="3.15/2.6")
    chk("both colours of the same design become rows",pg.evaluate("JSON.stringify(getRows())")=='[{"colour":"P53","qty":30},{"colour":"P54","qty":20}]')
    chk("karigar from photo kept as master name",pg.evaluate("f_karigar.value")=="RUSTAM")
    pg.locator("[data-act=save]").click(); pg.wait_for_timeout(300)
    chk("challan 1551 has 2 lines",pg.evaluate("D.issues.filter(x=>x.challan=='1551').length")==2)
    chk("each line has its colour and qty",pg.evaluate("D.issues.filter(x=>x.challan=='1551').map(x=>x.colour+':'+x.qty).sort().join(',')")=="P53:30,P54:20")
    pg.evaluate("doPrint('challan','1551')"); pg.wait_for_timeout(150)
    chk("print whole challan renders both items",pg.evaluate("(document.getElementById('pv')||{innerText:''}).innerText.includes('P53')")) 
    # job card order with text fabric names (regression: used to fail the F-number check)
    pg.locator("nav button",has_text="TNA").first.click(); pg.locator("[data-act=onew]").click(); pg.wait_for_timeout(150)
    pg.evaluate("""()=>fillAI({jobCard:'P256',orderDate:'2026-07-24',design:'SD 11071',qty:100,orderType:'Expo-Order',topFab:'Mal Chanderi',botFab:'Cotton',accessories:'Lace + Funda',colours:['P53','P54'],remarks:'Deep shade single'},'orders')""")
    pg.locator("[data-act=save]").click(); pg.wait_for_timeout(300)
    chk("order saved with fabric NAME (spaces kept)",pg.evaluate("(D.orders.find(o=>o.jobCard==='P256')||{}).topFab")=="Mal Chanderi")
    t=pg.locator("#L").inner_text(); chk("TNA card shows colours and accessories","P53" in t and "Lace" in t)
    # weighted average costing
    pg.locator("nav button",has_text="Cost").first.click(); pg.locator("[data-act=cost][data-id=GF26S271]").click(); pg.wait_for_timeout(250)
    txt=pg.locator(".ov").inner_text(); chk("fabric F005 weighted average 124.17",("124.17" in txt))
    chk("job work weighted average for 154 pcs lots",("612.6" in txt))
    pg.locator("#cx").click()
    # ledger maths (Rs 9375 gross -> 141 std, 93 tds, 9141 net is checked by the unit formula)
    pg.evaluate("D.payments.length"); 
    for role,must in [("staff",["Issue"]),("admin",["Issue"])]:
        pg.select_option("#drole",role); pg.wait_for_timeout(200)
        tb=[x.inner_text() for x in pg.locator("nav button").all()]
        chk(role+" has no Cost / Ledger tab","Cost" not in tb and "Ledger" not in tb)
    pg.select_option("#drole","subl"); pg.wait_for_timeout(200)
    chk("sub admin + ledger tick sees Ledger","Ledger" in [x.inner_text() for x in pg.locator("nav button").all()])
    # sample TNA tab (separate from production TNA)
    pg.select_option("#drole","super"); pg.wait_for_timeout(200)
    pg.locator("nav button",has_text="Sample TNA").first.click(); pg.wait_for_timeout(250)
    st=pg.locator("#L").inner_text()
    chk("Sample TNA lists SMP-01 with party and 3 stages of lots","SMP-01" in st and "BANGALORE AGENT" in st)
    chk("production TNA does not list the sample", "SMP-01" not in (pg.locator("nav button",has_text="TNA").first.click() or "") + pg.locator("#L").inner_text())
    pg.locator("nav button",has_text="Sample TNA").first.click(); pg.locator("[data-act=onew][data-v=sample]").click(); pg.wait_for_timeout(200)
    chk("new sample form is titled New sample","New sample" in pg.locator("#F").inner_text())
    pg.evaluate("()=>{const s=(i,v)=>document.getElementById('f_'+i).value=v;s('jobCard','SMP-02');s('design','TY0123');s('qty','2')}")
    pg.locator("[data-act=save]").click(); pg.wait_for_timeout(300)
    chk("new sample saved with kind=sample",pg.evaluate("(D.orders.find(o=>o.jobCard==='SMP-02')||{}).kind")=="sample" and pg.evaluate("TAB")=="sample")
    # alteration flow
    pg.locator("nav button",has_text="Alter").first.click(); pg.wait_for_timeout(250)
    chk("alteration tab shows pending total","In alteration now: 4 pcs" in pg.locator("#L").inner_text())
    pg.evaluate("()=>{const s=(i,v)=>document.getElementById('f_'+i).value=v;s('challan','ALT-2');s('design','SD11068');s('karigar','MAHMOOD ALAM');s('qty','5');s('rate','30');s('reason','shade lighter');}")
    pg.select_option("#f_altType","Dyeing (re-dye)")
    pg.locator("[data-act=save]").click(); pg.wait_for_timeout(300)
    chk("alteration saved",pg.evaluate("D.alters.some(x=>x.challan==='ALT-2'&&x.qty===5)"))
    pg.locator("[data-act=arecv]").first.click(); pg.wait_for_timeout(200)
    pg.evaluate("document.getElementById('aq').value=3"); pg.locator("#as").click(); pg.wait_for_timeout(300)
    chk("partial return recorded (pending drops)",pg.evaluate("(()=>{const x=D.alters.find(y=>y.challan==='ALT-2'||y.returns&&y.returns.length&&y.challan!=='ALT-1');return altPend(D.alters.find(y=>y.challan==='ALT-2'))})()")==2)
    pg.locator("nav button",has_text="Stock").first.click(); pg.wait_for_timeout(250)
    t=pg.locator("#L").inner_text(); i=t.find("SD11068")
    chk("stock row shows In alteration",("In alteration" in t[i:i+260]))
    chk("ledger includes alteration amount for ASADUL",pg.evaluate("ledgerTot('ASADUL').g")==2*40)
    pg.evaluate("doPrint('alters',D.alters.find(x=>x.challan==='ALT-2').id)"); pg.wait_for_timeout(150)
    chk("alteration challan prints",pg.evaluate("(document.getElementById('pv')||{innerText:''}).innerText.includes('ALTERATION CHALLAN')"))
    # karigar picker is filtered by the alteration work category
    pg.locator("nav button",has_text="Alter").first.click(); pg.wait_for_timeout(150)
    pg.select_option("#f_altType","Piping repair"); pg.locator("#f_karigar").click(); pg.wait_for_timeout(200)
    chk("karigar list filtered to Tailor / Finishing for piping repair","Tailor / Finishing" in pg.locator(".ov").inner_text())
    pg.locator("#px").click()
    # ---- v13 features
    chk("nearest karigar name from handwriting",pg.evaluate("nearest('Alim Mistry',D.karigars.map(x=>x.name))")=="ALIM MISTRI (KATHA)" and pg.evaluate("nearest('Rustam bhai',D.karigars.map(x=>x.name))")=="RUSTAM" and pg.evaluate("nearest('Zzqx Plk',D.karigars.map(x=>x.name))") is None)
    pg.locator("nav button",has_text="Issue").first.click(); pg.wait_for_timeout(150)
    pg.evaluate("""()=>fillAI({challan:'1600',karigar:'Rustm',items:[{design:'SD11068',colour:'P1',qty:5,total:5.75,topFab:'F158'},{design:'SD11068',colour:'P2',qty:6,total:5.75,topFab:'F158'},{design:'RZ0038',colour:'D3',qty:7,total:5.6,topFab:'F158'}]},'issues')""")
    chk("photo with 2 designs: first design rows, second queued",pg.evaluate("getRows().length")==2 and pg.evaluate("QUEUE.length")==1 and pg.evaluate("f_karigar.value")=="RUSTAM")
    pg.locator("[data-act=savenext]").click(); pg.wait_for_timeout(300)
    chk("next design prefilled with its colour row",pg.evaluate("f_design.value")=="RZ0038" and pg.evaluate("JSON.stringify(getRows())")=='[{"colour":"D3","qty":7}]' and pg.evaluate("f_challan.value")=="1600")
    pg.locator("[data-act=save]").click(); pg.wait_for_timeout(300)
    chk("challan 1600 has 3 lines",pg.evaluate("D.issues.filter(x=>x.challan=='1600').length")==3)
    # colours from the job card (P256 saved above with P53, P54)
    pg.evaluate("()=>{f_challan.value='1700';f_karigar.value='RUSTAM';f_design.value='SD11071';f_jobCard.value='P256';afterPick('jobCard')}")
    chk("colours from job card fill the rows",pg.evaluate("getRows().map(r=>r.colour).join(',')")=="P53,P54")
    # sample issue: no metres needed, flagged SAMPLE
    pg.evaluate("()=>{f_jobCard.value='SMP-01';afterPick('jobCard');setRows([{colour:'P9',qty:1}]);f_total.value='';f_topMtr.value='';f_dupMtr.value=''}")
    chk("sample job card ticks SAMPLE",pg.evaluate("f_sample.checked"))
    pg.locator("[data-act=save]").click(); pg.wait_for_timeout(300)
    chk("sample issue saved with sample flag",pg.evaluate("D.issues.some(x=>x.challan==='1700'&&x.sample===true&&x.qty===1)"))
    chk("issue list shows SAMPLE tag","SAMPLE" in pg.locator("#L").inner_text())
    # order form: brand from design prefix, colour chips, fabric names
    pg.locator("nav button",has_text="TNA").first.click(); pg.locator("[data-act=onew]").first.click(); pg.wait_for_timeout(150)
    pg.evaluate("()=>{f_design.value='MH0123';afterPick('design')}"); chk("brand MAHARANI from MH",pg.evaluate("f_brand.value")=="MAHARANI")
    pg.evaluate("()=>{f_design.value='RZ0152';afterPick('design')}"); chk("brand follows the design (ROZANA)",pg.evaluate("f_brand.value")=="ROZANA")
    pg.locator("#f_colours").click(); pg.wait_for_timeout(150)
    chk("colour list has P100, D50, M50",all(pg.locator(".ov [data-v=%s]"%c).count()==1 for c in ["P100","D50","M50"]))
    for c in ["P5","P7","D2","M11"]: pg.locator(".ov [data-v=%s]"%c).click()
    pg.locator("#ok2").click(); pg.wait_for_timeout(100)
    chk("multi colour value",pg.evaluate("f_colours.value")=="P5, P7, D2, M11")
    pg.locator("#f_topFab").click(); pg.wait_for_timeout(150)
    names=[x.inner_text().split("\n")[1] if "\n" in x.inner_text() else "" for x in pg.locator(".ov #pl .row").all()]
    chk("fabric list sorted by name",names==sorted(names) and len(names)>=4)
    pg.locator(".ov #pl .row",has_text="MUL CHANDERI").first.click(); chk("fabric picked as F no",pg.evaluate("f_topFab.value")=="F158")
    chk("design no GF26S271 accepted",pg.evaluate("chk({design:'GF26S271'},true)")=="")
    chk("no JS errors",not errs)
    if errs: print(errs)
    b.close()
sys.exit(0 if all(c for _,c in res) else 1)
